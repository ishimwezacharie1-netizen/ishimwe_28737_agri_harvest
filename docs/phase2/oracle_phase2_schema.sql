-- Phase II normalized Oracle schema for the Rwanda HarvestStat extract.
-- Oracle Database 12c or later. This is design DDL; execute the install/load
-- scripts during the database and data-loading phases, not in an existing schema.

CREATE TABLE source_dataset (
    dataset_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dataset_code VARCHAR2(100) NOT NULL UNIQUE,
    dataset_name VARCHAR2(255) NOT NULL,
    source_url VARCHAR2(500) NOT NULL,
    license_name VARCHAR2(255),
    license_reviewed_at DATE,
    attribution_text VARCHAR2(1000),
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE import_batch (
    batch_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dataset_id NUMBER NOT NULL,
    batch_code VARCHAR2(100) NOT NULL,
    file_name VARCHAR2(255) NOT NULL,
    import_status VARCHAR2(20) DEFAULT 'STAGED' NOT NULL
        CHECK (import_status IN ('STAGED', 'VALIDATED', 'LOADED', 'REJECTED')),
    imported_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    total_rows NUMBER DEFAULT 0 NOT NULL,
    loaded_rows NUMBER DEFAULT 0 NOT NULL,
    rejected_rows NUMBER DEFAULT 0 NOT NULL,
    CONSTRAINT uq_import_batch_dataset UNIQUE (batch_id, dataset_id),
    CONSTRAINT uq_import_dataset_code UNIQUE (dataset_id, batch_code),
    CONSTRAINT fk_import_dataset FOREIGN KEY (dataset_id)
        REFERENCES source_dataset(dataset_id),
    CONSTRAINT ck_import_counts CHECK (
        total_rows >= 0 AND loaded_rows >= 0 AND rejected_rows >= 0
        AND loaded_rows + rejected_rows <= total_rows
    )
);

CREATE TABLE source_document (
    source_document_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dataset_id NUMBER NOT NULL,
    source_document_code VARCHAR2(50) NOT NULL,
    source_document_name VARCHAR2(500) NOT NULL,
    source_organization_code VARCHAR2(50),
    source_organization_name VARCHAR2(500),
    CONSTRAINT uq_source_document UNIQUE (dataset_id, source_document_code),
    CONSTRAINT fk_source_document_dataset FOREIGN KEY (dataset_id)
        REFERENCES source_dataset(dataset_id)
);

CREATE TABLE admin_1 (
    admin_1_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_1_name VARCHAR2(100) NOT NULL UNIQUE
);

CREATE TABLE admin_2 (
    admin_2_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_2_name VARCHAR2(100) NOT NULL UNIQUE,
    admin_1_id NUMBER NOT NULL,
    CONSTRAINT fk_admin_2_admin_1 FOREIGN KEY (admin_1_id)
        REFERENCES admin_1(admin_1_id)
);

CREATE TABLE admin_area (
    fnid VARCHAR2(50) PRIMARY KEY,
    geographic_unit_name VARCHAR2(200) NOT NULL,
    geographic_unit_full_name VARCHAR2(500),
    admin_2_id NUMBER,
    legacy_admin_1_id NUMBER,
    CONSTRAINT ck_admin_area_level CHECK (
        (admin_2_id IS NOT NULL AND legacy_admin_1_id IS NULL)
        OR (admin_2_id IS NULL AND legacy_admin_1_id IS NOT NULL)
    ),
    CONSTRAINT fk_admin_area_admin_2 FOREIGN KEY (admin_2_id)
        REFERENCES admin_2(admin_2_id),
    CONSTRAINT fk_admin_area_legacy_admin_1 FOREIGN KEY (legacy_admin_1_id)
        REFERENCES admin_1(admin_1_id)
);

CREATE TABLE crop (
    crop_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    crop_code VARCHAR2(50) NOT NULL UNIQUE,
    crop_name VARCHAR2(200) NOT NULL UNIQUE,
    crop_description VARCHAR2(300)
);

CREATE TABLE indicator (
    indicator_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    indicator_code VARCHAR2(50) NOT NULL UNIQUE,
    indicator_name VARCHAR2(100) NOT NULL UNIQUE,
    allowed_unit VARCHAR2(30) NOT NULL,
    unit_name VARCHAR2(100) NOT NULL,
    CONSTRAINT uq_indicator_unit UNIQUE (indicator_id, allowed_unit)
);

CREATE TABLE season (
    season_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    season_name VARCHAR2(50) NOT NULL UNIQUE
);

CREATE TABLE season_year (
    season_year_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    season_id NUMBER NOT NULL,
    observation_year NUMBER(4) NOT NULL,
    season_year_label VARCHAR2(50) NOT NULL UNIQUE,
    start_date DATE,
    period_date DATE,
    season_date DATE,
    CONSTRAINT uq_season_year UNIQUE (season_id, observation_year),
    CONSTRAINT fk_season_year_season FOREIGN KEY (season_id)
        REFERENCES season(season_id),
    CONSTRAINT ck_season_year CHECK (observation_year BETWEEN 1000 AND 9999)
);

-- Raw staging retains the 39 nonconstant source fields (including the source
-- id renamed source_record_id). Numeric/date-like values remain text until
-- validated, preserving malformed source values for quality review.
CREATE TABLE stage_crop_observation (
    stage_row_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id NUMBER,
    source_organization VARCHAR2(500),
    source_document VARCHAR2(500),
    geographic_unit_full_name VARCHAR2(500),
    geographic_unit_name VARCHAR2(200),
    fnid VARCHAR2(50),
    admin_1 VARCHAR2(100),
    admin_2 VARCHAR2(100),
    start_date_raw VARCHAR2(40),
    period_date_raw VARCHAR2(40),
    season_name VARCHAR2(50),
    season_date_raw VARCHAR2(40),
    season_year VARCHAR2(50),
    indicator_name VARCHAR2(100),
    source_status VARCHAR2(50),
    value_raw VARCHAR2(100),
    population_raw VARCHAR2(100),
    value_per_capita_raw VARCHAR2(100),
    product_name VARCHAR2(200),
    locality_name VARCHAR2(200),
    unit_code VARCHAR2(30),
    unit_name VARCHAR2(100),
    crop_code VARCHAR2(50),
    crop_description VARCHAR2(300),
    source_record_id VARCHAR2(50) NOT NULL,
    data_collection_period VARCHAR2(50),
    data_collection_code VARCHAR2(50),
    source_document_code VARCHAR2(50),
    source_organization_code VARCHAR2(50),
    indicator_code VARCHAR2(50),
    locality_code VARCHAR2(50),
    geographic_unit_code VARCHAR2(50),
    season_code VARCHAR2(50),
    data_series VARCHAR2(1000),
    data_series_name VARCHAR2(1000),
    created_raw VARCHAR2(40),
    modified_raw VARCHAR2(40),
    status_changed_raw VARCHAR2(40),
    collection_status_changed_raw VARCHAR2(40),
    collection_date_raw VARCHAR2(40),
    row_status VARCHAR2(20) DEFAULT 'PENDING' NOT NULL
        CHECK (row_status IN ('PENDING', 'ACCEPTED', 'REJECTED')),
    CONSTRAINT fk_stage_batch FOREIGN KEY (batch_id)
        REFERENCES import_batch(batch_id),
    CONSTRAINT uq_stage_source_record UNIQUE (batch_id, source_record_id)
);

CREATE TABLE agg_crop_statistic (
    statistic_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id NUMBER NOT NULL,
    source_document_id NUMBER,
    fnid VARCHAR2(50) NOT NULL,
    crop_id NUMBER NOT NULL,
    indicator_id NUMBER NOT NULL,
    season_year_id NUMBER NOT NULL,
    source_record_id VARCHAR2(50) NOT NULL,
    numeric_value NUMBER(18,8) NOT NULL,
    quality_status VARCHAR2(20) DEFAULT 'VALID' NOT NULL
        CHECK (quality_status IN ('VALID', 'FLAGGED', 'CORRECTED')),
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT uq_stat_natural_key UNIQUE (fnid, crop_id, indicator_id, season_year_id),
    CONSTRAINT uq_stat_source_record UNIQUE (source_record_id),
    CONSTRAINT ck_stat_value CHECK (numeric_value >= 0),
    CONSTRAINT fk_stat_batch FOREIGN KEY (batch_id)
        REFERENCES import_batch(batch_id),
    CONSTRAINT fk_stat_source_document FOREIGN KEY (source_document_id)
        REFERENCES source_document(source_document_id),
    CONSTRAINT fk_stat_area FOREIGN KEY (fnid) REFERENCES admin_area(fnid),
    CONSTRAINT fk_stat_crop FOREIGN KEY (crop_id) REFERENCES crop(crop_id),
    CONSTRAINT fk_stat_indicator FOREIGN KEY (indicator_id) REFERENCES indicator(indicator_id),
    CONSTRAINT fk_stat_season_year FOREIGN KEY (season_year_id)
        REFERENCES season_year(season_year_id)
);

CREATE TABLE data_quality_issue (
    issue_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stage_row_id NUMBER,
    statistic_id NUMBER,
    issue_type VARCHAR2(40) NOT NULL
        CHECK (issue_type IN (
            'MISSING_VALUE', 'INVALID_VALUE', 'INVALID_UNIT', 'DUPLICATE_RECORD',
            'INVALID_PERIOD', 'UNRESOLVED_KEY', 'REJECTED_IMPORT'
        )),
    severity VARCHAR2(20) DEFAULT 'MEDIUM' NOT NULL
        CHECK (severity IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    issue_description VARCHAR2(1000) NOT NULL,
    reported_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    resolved_flag CHAR(1) DEFAULT 'N' NOT NULL
        CHECK (resolved_flag IN ('Y', 'N')),
    CONSTRAINT ck_quality_issue_target CHECK (
        stage_row_id IS NOT NULL OR statistic_id IS NOT NULL
    ),
    CONSTRAINT fk_quality_stage FOREIGN KEY (stage_row_id)
        REFERENCES stage_crop_observation(stage_row_id),
    CONSTRAINT fk_quality_stat FOREIGN KEY (statistic_id)
        REFERENCES agg_crop_statistic(statistic_id)
);

CREATE TABLE data_correction_request (
    correction_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    statistic_id NUMBER NOT NULL,
    requested_by VARCHAR2(100) NOT NULL,
    request_date TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    original_value NUMBER(18,8) NOT NULL,
    proposed_value NUMBER(18,8) NOT NULL,
    reason_text CLOB NOT NULL,
    evidence_text CLOB,
    request_status VARCHAR2(20) DEFAULT 'PENDING' NOT NULL
        CHECK (request_status IN ('PENDING', 'APPROVED', 'REJECTED', 'APPLIED')),
    reviewer_user VARCHAR2(100),
    reviewed_at TIMESTAMP,
    CONSTRAINT ck_correction_values CHECK (original_value >= 0 AND proposed_value >= 0),
    CONSTRAINT fk_correction_stat FOREIGN KEY (statistic_id)
        REFERENCES agg_crop_statistic(statistic_id)
);

CREATE TABLE audit_event (
    audit_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    statistic_id NUMBER NOT NULL,
    correction_id NUMBER,
    old_value NUMBER(18,8),
    new_value NUMBER(18,8),
    changed_by VARCHAR2(100) NOT NULL,
    changed_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    change_reason VARCHAR2(1000),
    CONSTRAINT fk_audit_stat FOREIGN KEY (statistic_id)
        REFERENCES agg_crop_statistic(statistic_id),
    CONSTRAINT fk_audit_correction FOREIGN KEY (correction_id)
        REFERENCES data_correction_request(correction_id)
);
