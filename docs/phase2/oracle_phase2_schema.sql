-- Phase 2 Oracle schema for the Agricultural Production and Harvest Tracking System
-- This design supports benchmark analytics, import validation, correction workflow, and auditability.

CREATE TABLE source_dataset (
    dataset_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dataset_code VARCHAR2(100) NOT NULL UNIQUE,
    dataset_name VARCHAR2(255) NOT NULL,
    organization_name VARCHAR2(255),
    source_url VARCHAR2(500),
    license_name VARCHAR2(255),
    license_url VARCHAR2(500),
    file_name VARCHAR2(255),
    version_label VARCHAR2(50),
    retrieval_date DATE,
    notes CLOB,
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE import_batch (
    batch_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dataset_id NUMBER NOT NULL,
    batch_code VARCHAR2(100) NOT NULL,
    file_name VARCHAR2(255) NOT NULL,
    import_status VARCHAR2(30) DEFAULT 'STAGED'
        CHECK (import_status IN ('STAGED', 'VALIDATED', 'REJECTED', 'LOADED', 'ARCHIVED')),
    imported_by VARCHAR2(100),
    imported_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    total_rows NUMBER DEFAULT 0,
    accepted_rows NUMBER DEFAULT 0,
    rejected_rows NUMBER DEFAULT 0,
    notes CLOB,
    CONSTRAINT fk_import_batch_dataset FOREIGN KEY (dataset_id)
        REFERENCES source_dataset(dataset_id),
    CONSTRAINT uq_import_batch_dataset UNIQUE (batch_id, dataset_id),
    CONSTRAINT uq_import_dataset_batch_code UNIQUE (dataset_id, batch_code)
);

CREATE TABLE stage_crop_observation (
    stage_row_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id NUMBER NOT NULL,
    dataset_id NUMBER NOT NULL,
    source_record_id VARCHAR2(100),
    source_record_hash VARCHAR2(128),
    product_name VARCHAR2(200),
    geographic_unit_name VARCHAR2(200),
    indicator_name VARCHAR2(150),
    source_status VARCHAR2(50),
    value_text VARCHAR2(200),
    unit_code VARCHAR2(30),
    season_name VARCHAR2(150),
    season_type VARCHAR2(50),
    season_year VARCHAR2(50),
    period_date DATE,
    row_status VARCHAR2(20) DEFAULT 'PENDING' NOT NULL
        CHECK (row_status IN ('PENDING', 'ACCEPTED', 'REJECTED')),
    loaded_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_stage_batch_dataset FOREIGN KEY (batch_id, dataset_id)
        REFERENCES import_batch(batch_id, dataset_id),
    CONSTRAINT uq_stage_source_record UNIQUE (batch_id, source_record_id)
);

CREATE TABLE admin_area (
    admin_area_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    area_code VARCHAR2(50),
    geographic_unit_name VARCHAR2(200) NOT NULL,
    country_code VARCHAR2(10) DEFAULT 'RW',
    historical_period VARCHAR2(50),
    admin_level VARCHAR2(30),
    parent_area_id NUMBER,
    is_active CHAR(1) DEFAULT 'Y'
        CHECK (is_active IN ('Y', 'N')),
    CONSTRAINT fk_admin_area_parent FOREIGN KEY (parent_area_id)
        REFERENCES admin_area(admin_area_id)
);

CREATE TABLE crop (
    crop_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    crop_code VARCHAR2(50) NOT NULL UNIQUE,
    crop_name VARCHAR2(200) NOT NULL,
    crop_group VARCHAR2(100),
    unit_group VARCHAR2(50),
    notes CLOB
);

CREATE TABLE season (
    season_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    season_code VARCHAR2(50) NOT NULL UNIQUE,
    season_name VARCHAR2(150) NOT NULL,
    year_number NUMBER NOT NULL,
    season_type VARCHAR2(50),
    remarks CLOB
);

CREATE TABLE indicator (
    indicator_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    indicator_code VARCHAR2(50) NOT NULL UNIQUE,
    indicator_name VARCHAR2(150) NOT NULL,
    description CLOB,
    allowed_unit VARCHAR2(30) NOT NULL,
    is_rate_indicator CHAR(1) DEFAULT 'N'
        CHECK (is_rate_indicator IN ('Y', 'N')),
    CONSTRAINT uq_indicator_unit UNIQUE (indicator_id, allowed_unit)
);

CREATE TABLE agg_crop_statistic (
    statistic_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id NUMBER NOT NULL,
    dataset_id NUMBER NOT NULL,
    source_record_id VARCHAR2(100) NOT NULL,
    admin_area_id NUMBER NOT NULL,
    crop_id NUMBER NOT NULL,
    season_id NUMBER NOT NULL,
    indicator_id NUMBER NOT NULL,
    numeric_value NUMBER(18,4) NOT NULL,
    unit_code VARCHAR2(30) NOT NULL,
    observation_year NUMBER,
    quality_status VARCHAR2(30) DEFAULT 'VALID'
        CHECK (quality_status IN ('VALID', 'FLAGGED', 'CORRECTED')),
    source_record_hash VARCHAR2(128),
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT ck_stat_value_nonnegative CHECK (numeric_value >= 0),
    CONSTRAINT uq_stat_source_record UNIQUE (dataset_id, source_record_id),
    CONSTRAINT fk_stat_batch_dataset FOREIGN KEY (batch_id, dataset_id)
        REFERENCES import_batch(batch_id, dataset_id),
    CONSTRAINT fk_stat_area FOREIGN KEY (admin_area_id) REFERENCES admin_area(admin_area_id),
    CONSTRAINT fk_stat_crop FOREIGN KEY (crop_id) REFERENCES crop(crop_id),
    CONSTRAINT fk_stat_season FOREIGN KEY (season_id) REFERENCES season(season_id),
    CONSTRAINT fk_stat_indicator_unit FOREIGN KEY (indicator_id, unit_code)
        REFERENCES indicator(indicator_id, allowed_unit)
);

CREATE TABLE data_quality_issue (
    issue_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stage_row_id NUMBER,
    statistic_id NUMBER,
    issue_type VARCHAR2(60) NOT NULL
        CHECK (issue_type IN ('MISSING_VALUE', 'INVALID_UNIT', 'DUPLICATE_RECORD', 'INVALID_PERIOD', 'REJECTED_IMPORT', 'INCOMPLETE_SOURCE')),
    severity VARCHAR2(20) DEFAULT 'MEDIUM'
        CHECK (severity IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    issue_description CLOB NOT NULL,
    reported_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    resolved_flag CHAR(1) DEFAULT 'N'
        CHECK (resolved_flag IN ('Y', 'N')),
    CONSTRAINT ck_quality_issue_target CHECK (stage_row_id IS NOT NULL OR statistic_id IS NOT NULL),
    CONSTRAINT fk_quality_issue_stage FOREIGN KEY (stage_row_id)
        REFERENCES stage_crop_observation(stage_row_id),
    CONSTRAINT fk_quality_issue_stat FOREIGN KEY (statistic_id)
        REFERENCES agg_crop_statistic(statistic_id)
);

CREATE TABLE data_correction_request (
    correction_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    statistic_id NUMBER NOT NULL,
    requested_by VARCHAR2(100) NOT NULL,
    request_date TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    original_value NUMBER(18,4),
    proposed_value NUMBER(18,4),
    reason_text CLOB NOT NULL,
    evidence_text CLOB,
    request_status VARCHAR2(30) DEFAULT 'PENDING'
        CHECK (request_status IN ('PENDING', 'APPROVED', 'REJECTED', 'APPLIED')),
    reviewer_user VARCHAR2(100),
    reviewed_at TIMESTAMP,
    CONSTRAINT fk_correction_stat FOREIGN KEY (statistic_id)
        REFERENCES agg_crop_statistic(statistic_id)
);

CREATE TABLE audit_event (
    audit_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    statistic_id NUMBER NOT NULL,
    correction_id NUMBER,
    old_value NUMBER(18,4),
    new_value NUMBER(18,4),
    changed_by VARCHAR2(100) NOT NULL,
    changed_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    change_reason VARCHAR2(255),
    application_context VARCHAR2(100),
    CONSTRAINT fk_audit_stat FOREIGN KEY (statistic_id)
        REFERENCES agg_crop_statistic(statistic_id),
    CONSTRAINT fk_audit_correction FOREIGN KEY (correction_id)
        REFERENCES data_correction_request(correction_id)
);

